"""Render :class:`MeetingNotes` as Markdown, JSON or a compact terminal view."""

from __future__ import annotations

import json
import os
import sys
from datetime import date

from .analyse import MeetingNotes


def to_json(notes: MeetingNotes) -> str:
    return json.dumps(notes.to_dict(), indent=2, ensure_ascii=False)


def _due(d: str | None) -> str:
    if not d:
        return "no date"
    return date.fromisoformat(d).strftime("%a %d %b")


def to_markdown(notes: MeetingNotes) -> str:
    out = [f"# {notes.title}", ""]
    meta = [f"**Date:** {notes.meeting_date}"]
    if notes.duration:
        meta.append(f"**Duration:** {notes.duration}")
    meta.append(f"**Participants:** {', '.join(f'{k} ({v:.0%})' for k, v in notes.participants.items())}")
    out += [" · ".join(meta), ""]
    out += ["## Summary", "", *[f"- {s}" for s in notes.summary], ""]
    if notes.topics:
        out += ["**Topics:** " + ", ".join(f"`{t}`" for t in notes.topics), ""]
    out += ["## Action items", ""]
    if notes.action_items:
        out += ["| | Task | Owner | Due | Priority |", "|---|---|---|---|---|"]
        for a in notes.action_items:
            flag = "🔴 high" if a.priority == "high" else "normal"
            out.append(f"| ☐ | {a.task} | {a.owner} | {_due(a.due)} | {flag} |")
    else:
        out.append("_No action items detected._")
    out.append("")
    out += ["## Decisions", ""]
    out += [f"- ✅ {d.text} — _{d.speaker}_" for d in notes.decisions] or ["_None recorded._"]
    out.append("")
    if notes.questions:
        out += ["## Questions raised", ""]
        for q in notes.questions:
            out.append(f"- **{q.speaker}:** {q.text}" + (f"  \n  ↳ {q.answer}" if q.answer else ""))
        out.append("")
    out.append(f"<sub>Generated by voice-notes-ai · transcription: {notes.engine} · analysis: {notes.analyser}</sub>")
    return "\n".join(out) + "\n"


def _c(code: str, s: str) -> str:
    on = os.getenv("FORCE_COLOR", "") not in ("", "0") or (sys.stdout.isatty() and not os.getenv("NO_COLOR"))
    return f"\033[{code}m{s}\033[0m" if on else s


def to_terminal(notes: MeetingNotes) -> str:
    lines = [_c("1;36", f"◆ {notes.title}"),
             _c("2", f"  {notes.meeting_date} · {notes.duration or '--:--'} · "
                     f"{len(notes.participants)} speakers · stt: {notes.engine} · analysis: {notes.analyser}"),
             "", _c("1", "Summary")]
    lines += [f"  • {s}" for s in notes.summary]
    if notes.topics:
        lines += ["", _c("1", "Topics ") + _c("2", " · ".join(notes.topics))]
    lines += ["", _c("1", f"Action items ({len(notes.action_items)})")]
    width = max((len(a.owner) for a in notes.action_items), default=5)
    for a in notes.action_items:
        pri = _c("31", "▲") if a.priority == "high" else _c("2", "·")
        lines.append(f"  {pri} {_c('33', a.owner.ljust(width))}  {a.task} {_c('2', '→ ' + _due(a.due))}")
    lines += ["", _c("1", f"Decisions ({len(notes.decisions)})")]
    lines += [f"  {_c('32', '✔')} {d.text}" for d in notes.decisions]
    if notes.questions:
        lines += ["", _c("1", f"Questions ({len(notes.questions)})")]
        lines += [f"  {_c('35', '?')} {q.text} {_c('2', '— ' + q.speaker)}" for q in notes.questions]
    return "\n".join(lines)
